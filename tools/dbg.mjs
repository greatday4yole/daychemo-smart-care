import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'chrome' })
const p = await b.newPage()
const errs = []
p.on('pageerror', e => errs.push(e.message))
p.on('console', m => { if (m.type()==='error') errs.push(m.text().slice(0,300)) })
await p.goto('http://localhost:4173/', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(600)
await p.getByText('李晓梅').first().click()
await p.waitForTimeout(600)
await p.locator('aside nav button', { hasText: '化疗前风险评估' }).first().click()
await p.waitForTimeout(600)
const cb = p.locator('input[type=checkbox]').first()
console.log('checkbox count', await p.locator('input[type=checkbox]').count(), 'checked', await cb.isChecked())
await cb.check()
console.log('after check', await cb.isChecked())
const btn = p.getByRole('button', { name: /提交评估并生成随访计划/ })
console.log('btn disabled', await btn.isDisabled())
await btn.click()
await p.waitForTimeout(800)
console.log('modal text count', await p.getByText('评估完成').count())
console.log('body has 已完成', (await p.locator('body').innerText()).includes('已完成'))
console.log('errors', errs)
await p.screenshot({ path: '/tmp/daychemo-shots/dbg-assess.png', fullPage: true })
await b.close()
