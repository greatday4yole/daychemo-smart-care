export const SopById = (id: string) => SOPS.find((s) => s.id === id)
export const sopForTerm = (termId: string, grade: number): SopDoc => {
  const candidates = SOPS.filter((s) => {
    if (termId === 'anc' || termId === 'wbc') return s.category === '骨髓抑制' && s.id.startsWith('sop-anc')
    if (termId === 'plt') return s.id === 'sop-plt-3'
    if (termId === 'allergy' || termId === 'rash') return s.category === '过敏反应'
    if (termId === 'extrav') return s.id === 'sop-extrav'
    if (termId === 'nausea' || termId === 'vomit' || termId === 'diarrhea' || termId === 'mucositis') return s.id === 'sop-gi'
    if (termId === 'fever' || termId === 'fn') return s.id === 'sop-fever' || s.id === 'sop-anc-3'
    return false
  })
  if (termId === 'fn') return SOPS.find((s) => s.id === 'sop-anc-3')!
  if (termId === 'fever') return SOPS.find((s) => s.id === 'sop-fever')!
  if (termId === 'plt') return SOPS.find((s) => s.id === 'sop-plt-3')!
  const best = candidates.find((s) => s.grade <= grade && s.grade >= Math.max(1, grade - 1)) ?? candidates[0]
  return best ?? SOPS.find((s) => s.id === 'sop-fever')!
}
