// 生成基于模板的提醒分发记录
const buildDispatches = (): ReminderDispatch[] => {
  const out: ReminderDispatch[] = []
  let n = 0
  for (const p of SEED_PATIENTS) {
    const chemoAt = new Date(`${p.chemoDate}T08:30:00`)
    for (const tpl of TEMPLATES) {
      if (!tpl.enabled) continue
      if (tpl.riskFilter !== 'all' && !tpl.riskFilter.includes(p.risk)) continue
      if (p.phase === 'post' && tpl.phase !== 'post') continue
      if (p.phase === 'pre' && tpl.phase === 'post') continue
      if (p.phase === 'during' && tpl.phase === 'post') continue
      const due = addHours(chemoAt, tpl.offsetHours)
      if (tpl.phase === 'post' && due.getTime() > Date.now() + 86_400_000 * 2) continue
      if (tpl.phase === 'pre' && due.getTime() > Date.now()) {
        // 保留即将触发的提醒
      }
      const past = due.getTime() < Date.now()
      out.push({
        id: `rd-${++n}`,
        patientId: p.id,
        templateId: tpl.id,
        title: tpl.title,
        body: tpl.body,
        dueAt: iso(due),
        channel: tpl.channel,
        status: past ? (n % 7 === 0 ? 'ack' : 'sent') : 'pending',
        readAt: past && n % 3 === 0 ? iso(due) : undefined,
        voicePlayedAt: past && tpl.channel.includes('voice') ? iso(due) : undefined,
      })
    }
  }
  return out
}

